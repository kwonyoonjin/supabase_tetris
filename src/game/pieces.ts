/** dir = 1 시계 방향, -1 반시계 방향 */
export function rotateMatrix(m: Matrix, dir: 1 | -1): Matrix {
  const n = m.length;
  return m.map((_, i) =>
    m.map((__, j) => (dir === 1 ? m[n - 1 - j][i] : m[j][n - 1 - i])),
  );
}

type Kick = readonly [number, number];

// 벽 차기 오프셋 (x 오른쪽 +, y 위쪽 +). 사용 시 y 부호를 뒤집어 보드 좌표(아래 +)로 바꾼다.
const KICKS_JLSTZ: Record<string, Kick[]> = {
  '0>1': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '1>0': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '1>2': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '2>1': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '2>3': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '3>2': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '3>0': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '0>3': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
};

const KICKS_I: Record<string, Kick[]> = {
  '0>1': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
  '1>0': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
  '1>2': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
  '2>1': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
  '2>3': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
  '3>2': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
  '3>0': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
  '0>3': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
};

/** 보드 좌표(아래쪽이 +y) 기준 오프셋 목록 */
export function getKicks(type: PieceType, from: number, to: number): Kick[] {
  if (type === 'O') return [[0, 0]];
  const table = type === 'I' ? KICKS_I : KICKS_JLSTZ;
  const kicks = table[`${from}>${to}`] ?? [[0, 0]];
  return kicks.map(([x, y]) => [x, -y] as const);
}
